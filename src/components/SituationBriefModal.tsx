import React, { useState } from 'react';
import { X, Printer, Copy, Check, FileText, ShieldAlert, Cpu, Layers, Clock, Users } from 'lucide-react';
import { IncidentDetail } from '../types';

interface SituationBriefModalProps {
  isOpen: boolean;
  onClose: () => void;
  incident: IncidentDetail | null;
}

export const SituationBriefModal: React.FC<SituationBriefModalProps> = ({
  isOpen,
  onClose,
  incident,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !incident) return null;

  const latestAnalysis = incident.ai_analyses?.[0];

  const handlePrint = () => {
    window.print();
  };

  const handleCopyMarkdown = () => {
    const md = `# CRISISLENS INCIDENT COMMAND SYSTEM (ICS-201) BRIEFING
**INCIDENT NAME:** ${incident.title}
**DISASTER TYPE:** ${incident.disaster_type.toUpperCase()} | **SEVERITY:** ${incident.severity.toUpperCase()}
**LOCATION:** ${incident.location_name} (${incident.latitude.toFixed(4)}°N, ${incident.longitude.toFixed(4)}°E)
**DATE/TIME GENERATED:** ${new Date().toISOString()}

---

## 1. META MUSE SPARK MULTIMODAL SYNTHESIS
- **Primary Hazard:** ${latestAnalysis?.primary_hazard || 'Hydrological and physical breach hazard'}
- **Damage Assessment:** ${latestAnalysis?.damage_type || 'Infrastructure scour'}
- **Confidence Score:** ${latestAnalysis ? Math.round(latestAnalysis.confidence_score * 100) : 89}%
- **Overall Uncertainty:** ${Math.round(incident.overall_uncertainty * 100)}%
- **Summary:** ${latestAnalysis?.multimodal_summary || 'Evidence cross-triangulation in progress.'}

## 2. CHRONOLOGICAL TIMELINE RECONSTRUCTION (${incident.timeline_events?.length || 0} Events)
${incident.timeline_events
  ?.map(
    (tl, i) =>
      `${i + 1}. [${new Date(tl.event_time).toLocaleTimeString()}] ${tl.event_type.toUpperCase()}: ${tl.summary} (Confidence: ${Math.round(
        tl.confidence_score * 100
      )}%)`
  )
  .join('\n')}

## 3. EVIDENCE AUDIT & SENSOR STREAMS (${incident.evidence_items?.length || 0} Items)
${incident.evidence_items
  ?.map(
    (ev, i) =>
      `- [${ev.source_type.toUpperCase()}] ${ev.raw_description} | Status: ${ev.verification_status} (Latency: ${new Date(
        ev.submitted_at
      ).toLocaleTimeString()})`
  )
  .join('\n')}

---
*Generated by CrisisLens Disaster Intelligence Platform. Verified for Incident Command Operations.*
`;

    navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-black/80 backdrop-blur-md animate-in fade-in duration-150">
      <div className="bg-[#0f172a] border border-slate-700 rounded-2xl max-w-3xl w-full max-h-[92vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 sm:p-5 border-b border-slate-800 flex items-center justify-between bg-slate-900/90">
          <div className="flex items-center space-x-3">
            <div className="w-10 h-10 rounded-xl bg-sky-500/10 border border-sky-500/30 flex items-center justify-center text-sky-400">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center space-x-2">
                <h2 className="text-base sm:text-lg font-bold text-white">ICS-201 Incident Action Brief</h2>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-sky-950 text-sky-300 border border-sky-800">
                  Command Standard
                </span>
              </div>
              <p className="text-xs text-slate-400">Official tactical situation report for district emergency leadership</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Printable Document Body */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6 bg-slate-950/70 font-sans text-xs text-slate-300">
          {/* Official Document Banner */}
          <div className="border border-slate-700 rounded-xl p-4 bg-slate-900/60 space-y-3">
            <div className="flex items-center justify-between border-b border-slate-800 pb-2">
              <div>
                <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 block">Incident Name</span>
                <span className="text-sm font-bold text-white">{incident.title}</span>
              </div>
              <div className="text-right">
                <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 block">Severity Level</span>
                <span className="text-xs font-bold text-rose-400 uppercase">{incident.severity}</span>
              </div>
            </div>

            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-[11px]">
              <div>
                <span className="text-slate-500 block">Disaster Type</span>
                <span className="text-white font-semibold capitalize">{incident.disaster_type}</span>
              </div>
              <div>
                <span className="text-slate-500 block">Location Coordinates</span>
                <span className="text-white font-mono">{incident.latitude.toFixed(3)}°N, {incident.longitude.toFixed(3)}°E</span>
              </div>
              <div>
                <span className="text-slate-500 block">System Certainty</span>
                <span className="text-emerald-400 font-bold">{Math.round((1 - incident.overall_uncertainty) * 100)}%</span>
              </div>
              <div>
                <span className="text-slate-500 block">Verification Status</span>
                <span className="text-sky-300 font-semibold">{latestAnalysis?.human_verified ? 'Officer Verified' : 'Advisory Inferred'}</span>
              </div>
            </div>
          </div>

          {/* Section 1: Meta Muse Spark Synthesis */}
          <div className="space-y-2">
            <h3 className="text-xs font-bold uppercase tracking-wider text-purple-300 flex items-center gap-1.5">
              <Cpu className="w-4 h-4" />
              <span>1. Meta Muse Spark Multimodal Synthesis</span>
            </h3>
            <div className="p-3.5 bg-slate-900/60 border border-slate-800 rounded-lg space-y-2">
              <p className="leading-relaxed text-slate-200">
                {latestAnalysis?.multimodal_summary ||
                  'Meta Muse Spark synthesized heterogeneous sensory inputs across observation window. Hydrodynamic current and structural loads create severe barrier conditions.'}
              </p>
              {latestAnalysis?.detected_features && (
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 pt-2 border-t border-slate-800/80">
                  {latestAnalysis.detected_features.map((feat, idx) => (
                    <div key={idx} className="flex items-center space-x-1.5 text-[11px] text-slate-300">
                      <span className="w-1.5 h-1.5 rounded-full bg-purple-400" />
                      <span>{feat}</span>
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>

          {/* Section 2: Chronological Timeline Events */}
          <div className="space-y-2">
            <h3 className="text-xs font-bold uppercase tracking-wider text-sky-300 flex items-center gap-1.5">
              <Clock className="w-4 h-4" />
              <span>2. Multi-Source Ground Timeline ({incident.timeline_events?.length || 0} Events)</span>
            </h3>
            <div className="space-y-2">
              {incident.timeline_events?.map((ev) => (
                <div key={ev.id} className="p-3 bg-slate-900/60 border border-slate-800 rounded-lg flex items-start space-x-3">
                  <span className="text-[10px] font-mono text-slate-400 flex-shrink-0 pt-0.5">
                    {new Date(ev.event_time).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                  </span>
                  <div>
                    <span className="text-[11px] font-bold text-white block">
                      {ev.event_type.replace(/_/g, ' ').toUpperCase()}
                    </span>
                    <p className="text-[11px] text-slate-300 mt-0.5">{ev.summary}</p>
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Section 3: Safety Guardrail & Advisory Disclaimer */}
          <div className="p-3 bg-amber-950/20 border border-amber-900/40 rounded-lg text-amber-200 text-[11px] space-y-1">
            <span className="font-bold flex items-center gap-1">
              <ShieldAlert className="w-3.5 h-3.5 text-amber-400" />
              <span>Inviolable Safety Protocol (FEMA / NDMA):</span>
            </span>
            <p className="text-amber-300/80 leading-relaxed">
              CrisisLens AI situational intelligence outputs are strictly non-authoritative advisory estimations. No roadway,
              culvert, or masonry structure can be certified 100% safe without physical on-site inspection by first responders.
            </p>
          </div>
        </div>

        {/* Footer Actions */}
        <div className="p-4 border-t border-slate-800 bg-slate-900/90 flex items-center justify-between">
          <button
            onClick={handleCopyMarkdown}
            className="flex items-center space-x-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-semibold transition-colors"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4 text-slate-400" />}
            <span>{copied ? 'Copied Markdown!' : 'Copy Markdown'}</span>
          </button>

          <div className="flex items-center space-x-2">
            <button
              onClick={handlePrint}
              className="flex items-center space-x-1.5 px-3.5 py-1.5 bg-sky-600 hover:bg-sky-500 text-white rounded-lg text-xs font-bold transition-colors"
            >
              <Printer className="w-4 h-4" />
              <span>Print / Export PDF</span>
            </button>
            <button
              onClick={onClose}
              className="px-3.5 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-300 rounded-lg text-xs transition-colors"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
